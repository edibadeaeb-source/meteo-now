const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const start=html.indexOf('function meteoInterval('),end=html.indexOf('// ── Variabile globale',start);
assert.ok(start>=0&&end>start);
const timers=[],window={setInterval(fn,delay){timers.push({fn,delay});return timers.length;}};
const context=vm.createContext({window,document:{hidden:false}});
vm.runInContext(html.slice(start,end),context);
let calls=0,receiver,args;
const id=context.meteoInterval(function(...values){calls++;receiver=this;args=values;},300000,'city',17);
assert.equal(id,1);timers[0].fn();assert.equal(calls,1);assert.equal(receiver,window);assert.deepEqual(args,['city',17]);
context.document.hidden=true;timers[0].fn();assert.equal(calls,1,'timers registered before preferences also stop while hidden');
context.document.hidden=false;context.AUTO_REFRESH=false;timers[0].fn();assert.equal(calls,1,'automatic refresh preference is respected');
context.meteoInterval(()=>calls++,1000);timers[1].fn();assert.equal(calls,2,'visible clock is independent of data refresh');
context.document.hidden=true;timers[1].fn();assert.equal(calls,2,'hidden clock does no work');
context.document.hidden=false;context.AUTO_REFRESH=true;timers[0].fn();assert.equal(calls,3,'existing timer resumes without duplicate registration');
assert.equal(timers.length,2);
assert.equal((html.match(/\bwindow\.setInterval\(/g)||[]).length,1);
assert.equal(/window\.setInterval\s*=/.test(html),false,'vendor and browser timers are not patched');
assert.equal(/(?<![.\w])setInterval\(/.test(html),false,'every app interval uses the early helper');
console.log('PASS: early timers, hidden clock and network callbacks, preference changes, resume, callback arguments and native vendor timers');
